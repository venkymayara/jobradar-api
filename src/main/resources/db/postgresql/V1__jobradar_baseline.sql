CREATE TABLE dbo.opportunities (
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title varchar(200) NOT NULL,
    company_id integer NOT NULL,
    location_id integer NOT NULL,
    work_mode varchar(20) NOT NULL,
    employment_type varchar(30) NOT NULL,
    min_experience integer NOT NULL,
    max_experience integer NOT NULL,
    min_salary numeric(15, 2),
    max_salary numeric(15, 2),
    currency_code varchar(3) NOT NULL DEFAULT 'INR',
    opportunity_type varchar(20) NOT NULL,
    description text NOT NULL,
    application_url varchar(2048),
    source_url varchar(2048),
    application_deadline date,
    status varchar(20) NOT NULL DEFAULT 'PENDING',
    is_verified boolean NOT NULL DEFAULT false,
    published_at timestamptz(6),
    created_by_user_id integer NOT NULL,
    created_at timestamptz(6) NOT NULL DEFAULT current_timestamp,
    updated_at timestamptz(6),
    created_by varchar(100),
    updated_by varchar(100),
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT pk_opportunities PRIMARY KEY (id),
    CONSTRAINT ck_opportunities_employment_type CHECK (employment_type='TEMPORARY' OR employment_type='INTERNSHIP' OR employment_type='CONTRACT' OR employment_type='PART_TIME' OR employment_type='FULL_TIME'),
    CONSTRAINT ck_opportunities_experience CHECK (min_experience>=(0) AND max_experience>=min_experience),
    CONSTRAINT ck_opportunities_published CHECK (status<>'ACTIVE' OR published_at IS NOT NULL),
    CONSTRAINT ck_opportunities_salary CHECK ((min_salary IS NULL OR min_salary>=(0)) AND (max_salary IS NULL OR max_salary>=(0)) AND (min_salary IS NULL OR max_salary IS NULL OR max_salary>=min_salary)),
    CONSTRAINT ck_opportunities_status CHECK (status='NEEDS_DETAILS' OR status='REMOVED' OR status='REJECTED' OR status='EXPIRED' OR status='FILLED' OR status='PAUSED' OR status='ACTIVE' OR status='PENDING' OR status='DRAFT'),
    CONSTRAINT ck_opportunities_type CHECK (opportunity_type='REFERRAL' OR opportunity_type='INTERNSHIP' OR opportunity_type='WALK_IN' OR opportunity_type='JOB'),
    CONSTRAINT ck_opportunities_verified CHECK (is_verified = false OR status='ACTIVE'),
    CONSTRAINT ck_opportunities_work_mode CHECK (work_mode='REMOTE' OR work_mode='HYBRID' OR work_mode='ON_SITE')
);

