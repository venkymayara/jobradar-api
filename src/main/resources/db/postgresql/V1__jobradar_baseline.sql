CREATE VIEW dbo.admin_user_directory AS
SELECT u.id AS user_id, u.username, COALESCE(NULLIF(TRIM(u.full_name), ''), u.username) AS display_name,
       EXISTS (SELECT 1 FROM dbo.user_roles r WHERE r.username = u.username AND r.role = 'ROLE_ADMIN') AS administrator,
       EXISTS (SELECT 1 FROM dbo.user_roles r WHERE r.username = u.username AND r.role = 'ROLE_MODERATOR') AS moderator,
       EXISTS (SELECT 1 FROM dbo.user_roles r WHERE r.username = u.username AND r.role = 'ROLE_SUPER_ADMIN') AS super_administrator
FROM dbo.users u;
